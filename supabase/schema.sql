-- Locações com todos os campos calculados (painel, listas e exportação).
-- Não traz CPF/CNPJ, e-mail nem telefone do locador.
create or replace view loc_locacoes_status with (security_invoker = true) as
select
  l.id, l.obra_id, o.nome as obra_nome, o.diretoria_id, dr.nome as diretoria_nome, o.gestor_nome,
  l.categoria_id, c.nome as categoria_nome, (d.locacao_id is not null) as e_imovel,
  l.descricao, l.fornecedor, l.foc, l.ftc, l.quantidade, l.valor_unitario, l.unidade, l.prazo,
  l.data_chegada, l.previsao_saida, l.aditivo_status, l.aditivo_data, l.data_devolucao, l.observacoes,
  l.criado_por_nome, l.criado_em, l.atualizado_por_nome, l.atualizado_em,
  d.fase, d.tipo_uso, d.termino_contrato, d.situacao_pagamento, d.capacidade, d.cidade_uf,
  e.encargos_ultra,
  r.fim_contratual, r.prazo_calculado, r.periodos_usados, r.valor_total_foc, r.saldo,
  r.mensal_base, r.custo_mensal, r.dias_fim, r.dias_prev, r.status, r.status_label, r.status_ordem,
  r.nota, r.acao, r.avisar_locador_ate, r.proximo_reajuste, r.dias_reajuste
from loc_locacoes l
join loc_obras o on o.id = l.obra_id
left join loc_diretorias dr on dr.id = o.diretoria_id
left join loc_categorias c on c.id = l.categoria_id
left join loc_imovel_detalhes d on d.locacao_id = l.id
cross join lateral (
  select case when d.locacao_id is null then 0::numeric else
      (case when d.iptu_quem = 'ultra' then coalesce(d.iptu_valor, 0) else 0 end)
    + (case when d.condominio_quem = 'ultra' then coalesce(d.condominio_valor, 0) else 0 end)
    + (case when d.agua_quem = 'ultra' then coalesce(d.agua_valor, 0) else 0 end)
    + (case when d.energia_quem = 'ultra' then coalesce(d.energia_valor, 0) else 0 end)
    + (case when d.internet_quem = 'ultra' then coalesce(d.internet_valor, 0) else 0 end)
  end as encargos_ultra
) e
cross join lateral loc_calcular(
  l.quantidade, l.valor_unitario, l.unidade, l.prazo, l.data_chegada, l.previsao_saida,
  l.aditivo_status, l.aditivo_data, l.data_devolucao, d.locacao_id is not null, d.termino_contrato,
  d.fase, d.aviso_previo_dias, d.indice_reajuste, e.encargos_ultra, loc_hoje()) r;

-- Histórico com nomes do item e da obra (usuário já com nomes juntados).
create or replace view loc_historico_view with (security_invoker = true) as
select
  h.id, h.em, h.acao, h.usuario_nome, coalesce(ud.nome, h.usuario_nome) as usuario,
  h.locacao_id, l.descricao as item_descricao, l.fornecedor as item_fornecedor,
  (d.locacao_id is not null) as e_imovel,
  coalesce(h.obra_id, l.obra_id) as obra_id, o.nome as obra_nome,
  h.referencia, h.resumo
from loc_historico h
left join loc_usuarios u on loc_normalizar(u.nome) = loc_normalizar(h.usuario_nome)
left join loc_usuarios ud on ud.id = u.unido_a_id
left join loc_locacoes l on l.id = h.locacao_id
left join loc_imovel_detalhes d on d.locacao_id = h.locacao_id
left join loc_obras o on o.id = coalesce(h.obra_id, l.obra_id);



create or replace function loc_renomear_categoria(p_usuario_nome text, p_id bigint, p_nome text) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  v_nome text := regexp_replace(trim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  v_antigo text;
begin
  select nome into v_antigo from loc_categorias where id = p_id;
  if v_antigo is null then raise exception 'Categoria não encontrada.'; end if;

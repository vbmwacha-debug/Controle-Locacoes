do $$
declare t text;
begin
  foreach t in array array['loc_diretorias', 'loc_usuarios', 'loc_obras', 'loc_categorias',
                           'loc_locacoes', 'loc_imovel_detalhes', 'loc_historico'] loop
    execute format('drop policy if exists loc_leitura on %I', t);

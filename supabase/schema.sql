-- Normaliza nomes para comparar sem diferenciar maiúsculas, acentos e espaços.
create or replace function loc_normalizar(p text) returns text
language sql immutable parallel safe as $$
  select regexp_replace(trim(lower(translate(coalesce(p, ''),
    'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑáàâãäéèêëíìîïóòôõöúùûüçñ',
    'AAAAAEEEEIIIIOOOOOUUUUCNaaaaaeeeeiiiiooooouuuucn'))), '\s+', ' ', 'g')
$$;

-- Hoje no fuso de São Paulo.
create or replace function loc_hoje() returns date
language sql stable as $$
  select (now() at time zone 'America/Sao_Paulo')::date
$$;

-- Nome da categoria especial de imóveis.
create or replace function loc_cat_imovel() returns text
language sql immutable as $$ select 'Imóvel (alojamento, casa, base, galpão)'::text $$;

create or replace function loc_fmt_data(p date) returns text
language sql immutable as $$ select to_char(p, 'DD/MM/YYYY') $$;

create or replace function loc_fmt_brl(p numeric) returns text
language sql immutable as $$
  select 'R$ ' || translate(to_char(round(p, 2), 'FM999,999,999,990.00'), ',.', '.,')
$$;

create or replace function loc_fmt_num(p numeric) returns text
language sql immutable as $$ select replace(trim_scale(p)::text, '.', ',') $$;

-- Soma um prazo na unidade: mês no calendário (fração de mês vira dias), semana = 7 dias, dia = 1 dia.
create or replace function loc_add_periodo(p_data date, p_n numeric, p_unidade text) returns date
language sql immutable as $$
  select case
    when p_data is null or p_n is null then null
    when p_unidade = 'dia' then p_data + round(p_n)::int
    when p_unidade = 'semana' then p_data + round(7 * p_n)::int
    else (p_data + make_interval(months => floor(p_n)::int))::date + round((p_n - floor(p_n)) * 30.4375)::int
  end
$$;

-- Meses entre duas datas, com 1 casa decimal (prazo dos imóveis).
create or replace function loc_meses_entre(a date, b date) returns numeric
language sql immutable as $$
  select round((
      (extract(year from b) - extract(year from a)) * 12
    + (extract(month from b) - extract(month from a))
    + (extract(day from b) - extract(day from a)) / 30.4375)::numeric, 1)
$$;

-- Próximo aniversário da data de início, depois de hoje e pelo menos 1 ano após o início.
create or replace function loc_proximo_aniversario(p_inicio date, p_hoje date) returns date
language plpgsql immutable as $$
declare
  anos int := greatest(1, (extract(year from p_hoje) - extract(year from p_inicio))::int);
  d date := (p_inicio + make_interval(years => anos))::date;
begin
  if d <= p_hoje then
    d := (p_inicio + make_interval(years => anos + 1))::date;
  end if;
  return d;
end $$;



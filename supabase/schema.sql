create or replace function loc_solicitar_aditivo(p_usuario_nome text, p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  l loc_locacoes;
  v_fim date;
begin
  select * into l from loc_locacoes where id = p_id;
  if not found then raise exception 'Item % não encontrado.', p_id; end if;
  if l.data_devolucao is not null then raise exception 'Este item já foi devolvido.'; end if;
  update loc_locacoes set aditivo_status = 'solicitado', aditivo_data = loc_hoje(),
    atualizado_por_nome = v, atualizado_em = now() where id = p_id;

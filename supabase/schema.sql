  perform loc_int_log(v, 'solicitou aditivo', p_id, l.obra_id, null,
    'Aditivo solicitado a Suprimentos' || coalesce(' · contrato vence em ' || loc_fmt_data(v_fim), ''));
end $$;

create or replace function loc_devolver(p_usuario_nome text, p_id bigint, p_data date default null) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  l loc_locacoes;
  v_data date := coalesce(p_data, loc_hoje());
  v_fase text;
begin
  select * into l from loc_locacoes where id = p_id;
  if not found then raise exception 'Item % não encontrado.', p_id; end if;
  if l.data_devolucao is not null then raise exception 'Este item já foi devolvido.'; end if;
  if v_data < l.data_chegada then raise exception 'A devolução não pode ser antes da chegada.'; end if;
  update loc_locacoes set data_devolucao = v_data, atualizado_por_nome = v, atualizado_em = now() where id = p_id;
  select fase into v_fase from loc_imovel_detalhes where locacao_id = p_id;
  if v_fase is not null and v_fase not in ('Desmobilizado', 'Encerrado') then
    update loc_imovel_detalhes set fase = 'Desmobilizado' where locacao_id = p_id;
  end if;
  perform loc_int_log(v, 'devolveu', p_id, l.obra_id, null,
    'Devolução em ' || loc_fmt_data(v_data)
    || case when v_fase is not null and v_fase not in ('Desmobilizado', 'Encerrado')
            then ' · Fase: ' || v_fase || ' → Desmobilizado' else '' end);
end $$;

create or replace function loc_salvar_obra(p_usuario_nome text, p_id bigint, p_nome text,
  p_diretoria_id bigint, p_gestor_nome text, p_ativa boolean default true) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  v_nome text := regexp_replace(trim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  o loc_obras;
  v_id bigint := p_id;
  v_res text := '';
  v_dir_a text;
  v_dir_b text;
begin
  if v_nome = '' then raise exception 'Preencha o nome da obra.'; end if;
  select nome into v_dir_b from loc_diretorias where id = p_diretoria_id;
  if v_dir_b is null then raise exception 'Escolha a diretoria.'; end if;
  if exists (select 1 from loc_obras where loc_normalizar(nome) = loc_normalizar(v_nome)
             and id is distinct from p_id) then
    raise exception 'Já existe uma obra com esse nome.';
  end if;
  if p_id is null then
    insert into loc_obras (nome, diretoria_id, gestor_nome, ativa)
    values (v_nome, p_diretoria_id, nullif(trim(p_gestor_nome), ''), coalesce(p_ativa, true))
    returning id into v_id;
    perform loc_int_log(v, 'criou', null, v_id, 'Obra: ' || v_nome,
      'Obra cadastrada · Diretoria ' || v_dir_b || coalesce(' · Gestor ' || nullif(trim(p_gestor_nome), ''), ''));
  else
    select * into o from loc_obras where id = p_id;
    if not found then raise exception 'Obra não encontrada.'; end if;
    select nome into v_dir_a from loc_diretorias where id = o.diretoria_id;
    update loc_obras set nome = v_nome, diretoria_id = p_diretoria_id,
      gestor_nome = nullif(trim(p_gestor_nome), ''), ativa = coalesce(p_ativa, true) where id = p_id;
    select string_agg(x, ' · ') into v_res from (values
      (case when o.nome <> v_nome then 'Nome: ' || o.nome || ' → ' || v_nome end),
      (case when v_dir_a <> v_dir_b then 'Diretoria: ' || v_dir_a || ' → ' || v_dir_b end),
      (case when coalesce(o.gestor_nome, '') <> coalesce(nullif(trim(p_gestor_nome), ''), '')
            then 'Gestor: ' || coalesce(o.gestor_nome, 'vazio') || ' → ' || coalesce(nullif(trim(p_gestor_nome), ''), 'vazio') end),
      (case when o.ativa <> coalesce(p_ativa, true)
            then 'Situação: ' || case when coalesce(p_ativa, true) then 'reativada' else 'encerrada' end end)) t(x);
    perform loc_int_log(v, 'editou', null, p_id, 'Obra: ' || v_nome, coalesce(v_res, 'Salvou sem mudanças'));
  end if;
  return v_id;
end $$;


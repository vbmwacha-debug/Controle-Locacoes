-- Retrato legível do item (nomes em português e valores formatados) para o histórico.
-- Dados pessoais do locador entram só como "impressão digital" (md5), nunca o valor.
create or replace function loc_int_snapshot(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_strip_nulls(
    jsonb_build_object(
      'Obra', o.nome, 'Categoria', c.nome, 'Descrição', l.descricao,
      case when x.im then 'Locador' else 'Fornecedor' end, l.fornecedor,
      'FOC', l.foc, 'FTC', l.ftc,
      'Quantidade', case when not x.im then loc_fmt_num(l.quantidade) end,
      case when x.im then 'Aluguel mensal' else 'Valor unitário' end, loc_fmt_brl(l.valor_unitario),
      'Unidade', case when not x.im then case l.unidade when 'mes' then 'mês' else l.unidade end end,
      'Prazo', case when not x.im then loc_fmt_num(l.prazo) end,
      case when x.im then 'Início da locação' else 'Data de chegada' end, loc_fmt_data(l.data_chegada),
      'Término do contrato', loc_fmt_data(d.termino_contrato),
      'Previsão de saída', loc_fmt_data(l.previsao_saida),
      'Aditivo', case when l.aditivo_status = 'solicitado' then 'solicitado' else 'não solicitado' end,
      'Data do aditivo', loc_fmt_data(l.aditivo_data),
      'Devolução', loc_fmt_data(l.data_devolucao),
      'Observações', l.observacoes)
    || case when x.im then jsonb_build_object(
      'Fase', d.fase, 'Nº cotação / MC', d.numero_cotacao, 'Tipo de uso', d.tipo_uso,
      'Endereço', d.endereco, 'Cidade/UF', d.cidade_uf, 'Capacidade', d.capacidade::text,
      'Alojados / uso', d.alojados, 'Locador PF/PJ', d.locador_tipo,
      'CPF / CNPJ do locador', md5(d.locador_documento), 'E-mail do locador', md5(d.locador_email),
      'Telefone do locador', md5(d.locador_telefone),
      'IPTU', loc_int_quem(d.iptu_quem, d.iptu_valor),
      'Condomínio', loc_int_quem(d.condominio_quem, d.condominio_valor),
      'Água', loc_int_quem(d.agua_quem, d.agua_valor),
      'Energia', loc_int_quem(d.energia_quem, d.energia_valor),
      'Internet', loc_int_quem(d.internet_quem, d.internet_valor),
      'Outros inclusos', d.outros_inclusos, 'Dia de vencimento', d.dia_vencimento::text,
      'Situação do pagamento', d.situacao_pagamento, 'Pendências', d.pendencias,
      'Índice de reajuste', d.indice_reajuste, 'Garantia', d.garantia,
      'Valor da garantia', loc_fmt_brl(d.valor_garantia),
      'Aviso prévio', d.aviso_previo_dias || ' dias',
      'Rescisão sem multa após', d.rescisao_sem_multa_apos_meses || ' meses',
      'Multa por atraso', d.multa_atraso)
    else '{}'::jsonb end)
  from loc_locacoes l
  join loc_obras o on o.id = l.obra_id
  left join loc_categorias c on c.id = l.categoria_id
  left join loc_imovel_detalhes d on d.locacao_id = l.id
  cross join lateral (select d.locacao_id is not null as im) x
  where l.id = p_id
$$;

-- "Previsão de saída: 03/08/2026 → 30/11/2026 · Fase: Ativo → Desmobilizar"
create or replace function loc_int_resumo(a jsonb, b jsonb) returns text
language sql immutable as $$
  select string_agg(
    case when k in ('CPF / CNPJ do locador', 'E-mail do locador', 'Telefone do locador') then k || ' alterado'
         else k || ': ' || coalesce(a ->> k, 'vazio') || ' → ' || coalesce(b ->> k, 'vazio') end,
    ' · ' order by ord)
  from unnest(loc_int_rotulos()) with ordinality t(k, ord)
  where (a ->> k) is distinct from (b ->> k)
$$;

-- Acha a categoria pelo nome (sem diferenciar maiúsculas e acentos) ou cria uma nova.
create or replace function loc_int_categoria(p_usuario text, p_nome text) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v text := regexp_replace(trim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  v_id bigint;
begin
  if v = '' then raise exception 'Escreva o nome da categoria.'; end if;
  select id into v_id from loc_categorias where loc_normalizar(nome) = loc_normalizar(v);
  if v_id is null then
    insert into loc_categorias (nome, sugerida, criado_por) values (v, false, p_usuario) returning id into v_id;
    perform loc_int_log(p_usuario, 'criou categoria', null, null, v, 'Categoria nova gravada na lista');
  end if;
  return v_id;
end $$;

-- Grava uma locação (nova ou existente) e o histórico na mesma transação.
-- p_dados: id, obra_id, categoria_id | categoria_nova, descricao, fornecedor, foc, ftc, quantidade,
--          valor_unitario, unidade, prazo, data_chegada, previsao_saida, aditivo_status, aditivo_data,
--          data_devolucao, observacoes, imovel { colunas de loc_imovel_detalhes }
create or replace function loc_int_gravar(p_usuario text, p_dados jsonb, p_planilha boolean) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_id bigint := nullif(p_dados ->> 'id', '')::bigint;
  v_novo boolean := v_id is null;
  v_obra bigint := nullif(p_dados ->> 'obra_id', '')::bigint;
  v_cat bigint;
  v_cat_nome text;
  v_im boolean;
  v_imd jsonb := coalesce(p_dados -> 'imovel', '{}'::jsonb);
  v_desc text := nullif(trim(p_dados ->> 'descricao'), '');
  v_forn text := nullif(trim(p_dados ->> 'fornecedor'), '');
  v_val numeric := nullif(p_dados ->> 'valor_unitario', '')::numeric;
  v_cheg date := nullif(p_dados ->> 'data_chegada', '')::date;
  v_term date;
  v_qtd numeric;
  v_unid text;
  v_prazo numeric;
  v_adit text := coalesce(nullif(p_dados ->> 'aditivo_status', ''), '');
  v_adit_data date := nullif(p_dados ->> 'aditivo_data', '')::date;
  v_antes jsonb;
  v_depois jsonb;
  v_resumo text;
  v_k text;
  v_q text;
  v_v numeric;
begin
  -- categoria
  if coalesce(trim(p_dados ->> 'categoria_nova'), '') <> '' then
    v_cat := loc_int_categoria(p_usuario, p_dados ->> 'categoria_nova');
  else
    v_cat := nullif(p_dados ->> 'categoria_id', '')::bigint;
  end if;
  select nome into v_cat_nome from loc_categorias where id = v_cat;
  if v_cat_nome is null then raise exception 'Escolha a categoria.'; end if;
  v_im := v_cat_nome = loc_cat_imovel();

  -- obrigatórios
  if v_obra is null or not exists (select 1 from loc_obras where id = v_obra) then
    raise exception 'Escolha a obra.';
  end if;
  if v_desc is null then raise exception 'Preencha a descrição.'; end if;
  if v_forn is null then
    raise exception '%', case when v_im then 'Preencha o locador.' else 'Preencha o fornecedor.' end;
  end if;
  if v_val is null then
    raise exception '%', case when v_im then 'Preencha o aluguel mensal.' else 'Preencha o valor unitário.' end;
  end if;
  if v_cheg is null then
    raise exception '%', case when v_im then 'Preencha o início da locação.' else 'Preencha a data de chegada.' end;
  end if;

  if v_im then
    v_term := nullif(v_imd ->> 'termino_contrato', '')::date;
    if v_term is null then raise exception 'Preencha o término do contrato.'; end if;
    if v_term <= v_cheg then raise exception 'O término do contrato precisa ser depois do início.'; end if;
    v_qtd := 1; v_unid := 'mes'; v_prazo := loc_meses_entre(v_cheg, v_term);
  else
    v_qtd := nullif(p_dados ->> 'quantidade', '')::numeric;
    v_unid := coalesce(nullif(p_dados ->> 'unidade', ''), 'mes');
    v_prazo := nullif(p_dados ->> 'prazo', '')::numeric;
    if v_qtd is null or v_qtd <= 0 then raise exception 'Preencha a quantidade.'; end if;
    if v_prazo is null or v_prazo <= 0 then raise exception 'O prazo deve ser maior que zero.'; end if;
  end if;
  if v_adit = 'solicitado' and v_adit_data is null then v_adit_data := loc_hoje(); end if;

  if v_novo then
    insert into loc_locacoes (obra_id, categoria_id, descricao, fornecedor, foc, ftc, quantidade, valor_unitario,
      unidade, prazo, data_chegada, previsao_saida, aditivo_status, aditivo_data, data_devolucao, observacoes,
      criado_por_nome)
    values (v_obra, v_cat, v_desc, v_forn, nullif(trim(p_dados ->> 'foc'), ''), nullif(trim(p_dados ->> 'ftc'), ''),
      v_qtd, v_val, v_unid, v_prazo, v_cheg, nullif(p_dados ->> 'previsao_saida', '')::date, v_adit, v_adit_data,
      nullif(p_dados ->> 'data_devolucao', '')::date, nullif(trim(p_dados ->> 'observacoes'), ''), p_usuario)
    returning id into v_id;
  else
    if not exists (select 1 from loc_locacoes where id = v_id) then
      raise exception 'Código % não existe no sistema.', v_id;
    end if;
    v_antes := loc_int_snapshot(v_id);
    update loc_locacoes set
      obra_id = v_obra, categoria_id = v_cat, descricao = v_desc, fornecedor = v_forn,
      foc = nullif(trim(p_dados ->> 'foc'), ''), ftc = nullif(trim(p_dados ->> 'ftc'), ''),
      quantidade = v_qtd, valor_unitario = v_val, unidade = v_unid, prazo = v_prazo, data_chegada = v_cheg,
      previsao_saida = nullif(p_dados ->> 'previsao_saida', '')::date, aditivo_status = v_adit,
      aditivo_data = v_adit_data, data_devolucao = nullif(p_dados ->> 'data_devolucao', '')::date,
      observacoes = nullif(trim(p_dados ->> 'observacoes'), ''),
      atualizado_por_nome = p_usuario, atualizado_em = now()
    where id = v_id;
  end if;

  -- detalhes do imóvel (1 para 1)
  delete from loc_imovel_detalhes where locacao_id = v_id;
  if v_im then
    select coalesce(jsonb_object_agg(key, value) filter (where value not in ('""'::jsonb, 'null'::jsonb)), '{}'::jsonb)
      into v_imd from jsonb_each(v_imd);
    foreach v_k in array array['iptu', 'condominio', 'agua', 'energia', 'internet'] loop
      v_q := v_imd ->> (v_k || '_quem');
      v_v := (v_imd ->> (v_k || '_valor'))::numeric;
      if v_q is null then v_q := case when coalesce(v_v, 0) > 0 then 'ultra' else 'na' end; end if;
      if v_q <> 'ultra' then v_v := null; end if;
      v_imd := v_imd || jsonb_build_object(v_k || '_quem', v_q, v_k || '_valor', v_v);
    end loop;
    v_imd := v_imd || jsonb_build_object('locacao_id', v_id, 'termino_contrato', v_term,
                                         'fase', coalesce(v_imd ->> 'fase', 'Ativo'));
    insert into loc_imovel_detalhes select * from jsonb_populate_record(null::loc_imovel_detalhes, v_imd);
  end if;

  v_depois := loc_int_snapshot(v_id);
  if v_novo then
    v_resumo := case when p_planilha then 'Importado da planilha · ' else '' end
      || case when v_im then 'Aluguel ' || loc_fmt_brl(v_val) || ' · término ' || loc_fmt_data(v_term)
              else 'Valor ' || loc_fmt_brl(v_val) || coalesce(' · FOC ' || nullif(trim(p_dados ->> 'foc'), ''), '') end;
  else
    v_resumo := coalesce(loc_int_resumo(v_antes, v_depois), 'Salvou sem mudanças');
    if p_planilha then v_resumo := 'Via planilha · ' || v_resumo; end if;
  end if;
  perform loc_int_log(p_usuario, case when v_novo then 'criou' else 'editou' end, v_id, v_obra,
                      null, v_resumo, v_antes, v_depois);
  return jsonb_build_object('id', v_id, 'novo', v_novo);
end $$;



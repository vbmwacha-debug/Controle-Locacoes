create or replace function loc_calcular(
  p_quantidade numeric, p_valor numeric, p_unidade text, p_prazo numeric,
  p_chegada date, p_previsao date, p_aditivo_status text, p_aditivo_data date, p_devolucao date,
  p_e_imovel boolean, p_termino date, p_fase text, p_aviso int, p_indice text, p_encargos_ultra numeric,
  p_hoje date,
  out fim_contratual date, out prazo_calculado numeric, out periodos_usados numeric,
  out valor_total_foc numeric, out saldo numeric, out mensal_base numeric, out custo_mensal numeric,
  out dias_fim int, out dias_prev int, out status text, out status_label text, out status_ordem int,
  out nota text, out acao text, out avisar_locador_ate date, out proximo_reajuste date, out dias_reajuste int)
language plpgsql immutable as $$
declare
  c_antecedencia constant int := 30;   -- dias para acionar Suprimentos antes do fim (ANTECEDENCIA)
  c_janela constant int := 15;         -- dias de "Programar devolução"
  c_atencao constant int := 60;        -- dias de "Vence em até 60 dias"
  v_im boolean := coalesce(p_e_imovel, false);
  v_unid text := case when v_im then 'mes' else coalesce(p_unidade, 'mes') end;
  v_qtd numeric := case when v_im then 1 else coalesce(p_quantidade, 0) end;
  v_aviso int := case when v_im then coalesce(p_aviso, 0) else 0 end;
  v_fase text := case when v_im then coalesce(p_fase, '') else '' end;
  v_adit boolean := coalesce(p_aditivo_status, '') = 'solicitado';
  v_por numeric;
begin
  if v_im then
    fim_contratual := p_termino;
    prazo_calculado := case when p_chegada is not null and p_termino is not null
                            then loc_meses_entre(p_chegada, p_termino) else 0 end;
  else
    fim_contratual := loc_add_periodo(p_chegada, coalesce(p_prazo, 0), v_unid);
    prazo_calculado := coalesce(p_prazo, 0);
  end if;

  if v_im and p_previsao is not null and v_aviso > 0 then
    avisar_locador_ate := p_previsao - v_aviso;
  end if;
  if v_im and p_chegada is not null and p_devolucao is null
     and p_indice is not null and p_indice <> 'Sem reajuste' then
    proximo_reajuste := loc_proximo_aniversario(p_chegada, p_hoje);
    dias_reajuste := proximo_reajuste - p_hoje;
  end if;

  periodos_usados := (case when p_chegada is null then 0
                           else greatest(0, coalesce(p_devolucao, p_hoje) - p_chegada) end)::numeric
                     / case v_unid when 'dia' then 1 when 'semana' then 7 else 30.4375 end;
  v_por := v_qtd * coalesce(p_valor, 0);
  valor_total_foc := v_por * prazo_calculado;
  saldo := valor_total_foc - v_por * periodos_usados;
  mensal_base := v_por * case v_unid when 'dia' then 30.4375 when 'semana' then 4.345 else 1 end;
  custo_mensal := mensal_base + case when v_im then coalesce(p_encargos_ultra, 0) else 0 end;
  dias_fim := fim_contratual - p_hoje;
  dias_prev := p_previsao - p_hoje;

  if p_devolucao is not null or v_fase in ('Desmobilizado', 'Encerrado') then
    status := 'encerrado';
    nota := case when p_devolucao is not null then 'Devolvido em ' || loc_fmt_data(p_devolucao)
                 else 'Fase: ' || v_fase end;
  elsif dias_fim < 0 then
    status := 'vencido';
    nota := 'Venceu há ' || (-dias_fim) || case when dias_fim = -1 then ' dia' else ' dias' end
         || case when v_adit then ' · aditivo solicitado' || coalesce(' em ' || loc_fmt_data(p_aditivo_data), '')
                 when v_fase = 'Tramitando' then ' · aditivo tramitando' else '' end;
  elsif v_fase = 'Mobilizar' then
    status := 'contratacao';
    nota := 'Ocupação prevista para ' || coalesce(loc_fmt_data(p_chegada), '—');
  elsif v_adit or v_fase = 'Tramitando' then
    status := 'aditamento';
    nota := coalesce('Solicitado em ' || loc_fmt_data(p_aditivo_data) || ' · ', '')
         || coalesce('contrato vence em ' || dias_fim || ' dias', 'aditivo em andamento');
  elsif dias_fim <= c_antecedencia and (p_previsao is null or p_previsao >= fim_contratual) then
    status := 'aditar';
    nota := 'Contrato vence em ' || dias_fim || ' dias'
         || coalesce('; obra precisa até ' || loc_fmt_data(p_previsao), '; sem previsão de saída');
  elsif dias_prev < 0 then
    status := 'atrasada';
    nota := 'Saída prevista para ' || loc_fmt_data(p_previsao) || ' (' || (-dias_prev) || ' dias atrás)';
  elsif v_fase = 'Desmobilizar' then
    status := 'programar';
    nota := case when avisar_locador_ate is not null and dias_prev is not null
                 then 'Desmobilização em andamento · avisar o locador até ' || loc_fmt_data(avisar_locador_ate)
                 else 'Desmobilização em andamento' || coalesce(' · saída em ' || dias_prev || ' dias', '') end;
  elsif dias_prev <= c_janela + v_aviso or dias_fim <= c_antecedencia then
    status := 'programar';
    nota := case when avisar_locador_ate is not null
                 then 'Avisar o locador até ' || loc_fmt_data(avisar_locador_ate) || ' (aviso de ' || v_aviso || ' dias)'
                 else 'Saída em ' || coalesce(dias_prev, dias_fim) || ' dias' end;
  elsif dias_fim <= c_atencao then
    status := 'atencao';
    nota := 'Contrato vence em ' || dias_fim || ' dias';
  elsif p_previsao > fim_contratual then
    status := 'prever';
    nota := 'Pedir aditivo até ' || loc_fmt_data(fim_contratual - c_antecedencia);
  else
    status := 'ok';
    nota := coalesce('Contrato vence em ' || dias_fim || ' dias', 'Sem data de fim contratual');
  end if;

  status_label := case status
    when 'vencido' then 'Vencido sem cobertura' when 'aditar' then 'Aditar agora'
    when 'atrasada' then 'Saída atrasada' when 'aditamento' then 'Em aditamento'
    when 'contratacao' then 'Em contratação' when 'programar' then 'Programar devolução'
    when 'atencao' then 'Vence em até 60 dias' when 'prever' then 'Prever aditivo'
    when 'ok' then 'Prazo OK' else 'Encerrado' end;
  status_ordem := case status
    when 'vencido' then 0 when 'aditar' then 1 when 'atrasada' then 2 when 'aditamento' then 3
    when 'contratacao' then 3 when 'programar' then 4 when 'atencao' then 5 when 'prever' then 5
    when 'ok' then 6 else 7 end;
  acao := case status
    when 'vencido' then 'Aditar ou devolver hoje. Pagamento vai travar.'
    when 'aditar' then 'Acionar Suprimentos: obra precisa além do contrato.'
    when 'atrasada' then 'Devolver ou atualizar a previsão de saída.'
    when 'aditamento' then 'Acompanhar aditivo com Suprimentos.'
    when 'contratacao' then 'Concluir contrato e FOC antes de ocupar.'
    when 'programar' then 'Agendar retirada com o fornecedor.'
    when 'atencao' then 'Confirmar se devolve ou adita.'
    when 'prever' then 'Previsão de saída passa do contrato.'
    else '' end;
end $$;



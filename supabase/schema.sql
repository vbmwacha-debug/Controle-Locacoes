-- Valida "nome e sobrenome", cria o usuário se for novo e devolve o nome oficial.
create or replace function loc_int_usuario(p_nome text) returns text
language plpgsql security definer set search_path = public as $$
declare
  v text := regexp_replace(trim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  u loc_usuarios;
begin
  if length(v) < 3 or position(' ' in v) = 0 then
    raise exception 'Informe nome e sobrenome para continuar.';
  end if;
  insert into loc_usuarios (nome) values (v) on conflict do nothing;
  select * into u from loc_usuarios where loc_normalizar(nome) = loc_normalizar(v);
  if u.unido_a_id is not null then
    select * into u from loc_usuarios where id = u.unido_a_id;
  end if;
  return u.nome;
end $$;


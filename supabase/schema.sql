create or replace function loc_juntar_categorias(p_usuario_nome text, p_origem_id bigint, p_destino_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  v_o text;
  v_d text;
  v_n int;
begin
  select nome into v_o from loc_categorias where id = p_origem_id;
  select nome into v_d from loc_categorias where id = p_destino_id;
  if v_o is null or v_d is null or p_origem_id = p_destino_id then raise exception 'Escolha duas categorias diferentes.'; end if;
  if loc_cat_imovel() in (v_o, v_d) then raise exception 'A categoria de imóveis não pode ser juntada.'; end if;
  update loc_locacoes set categoria_id = p_destino_id where categoria_id = p_origem_id;
  get diagnostics v_n = row_count;
  delete from loc_categorias where id = p_origem_id;
  perform loc_int_log(v, 'excluiu', null, null, 'Categoria: ' || v_o,
    'Categoria "' || v_o || '" juntada em "' || v_d || '" · ' || v_n || ' itens movidos');
end $$;

create or replace function loc_salvar_diretoria(p_usuario_nome text, p_id bigint, p_nome text, p_ativo boolean default true) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  v_nome text := regexp_replace(trim(coalesce(p_nome, '')), '\s+', ' ', 'g');
  d loc_diretorias;
  v_id bigint := p_id;
begin
  if v_nome = '' then raise exception 'Preencha o nome da diretoria.'; end if;
  if exists (select 1 from loc_diretorias where loc_normalizar(nome) = loc_normalizar(v_nome) and id is distinct from p_id) then
    raise exception 'Já existe uma diretoria com esse nome.';
  end if;
  if p_id is null then
    insert into loc_diretorias (nome, ativo) values (v_nome, coalesce(p_ativo, true)) returning id into v_id;
    perform loc_int_log(v, 'criou', null, null, 'Diretoria: ' || v_nome, 'Diretoria cadastrada');
  else
    select * into d from loc_diretorias where id = p_id;
    if not found then raise exception 'Diretoria não encontrada.'; end if;
    update loc_diretorias set nome = v_nome, ativo = coalesce(p_ativo, true) where id = p_id;
    perform loc_int_log(v, 'editou', null, null, 'Diretoria: ' || v_nome,
      coalesce(nullif(concat_ws(' · ',
        case when d.nome <> v_nome then 'Nome: ' || d.nome || ' → ' || v_nome end,
        case when d.ativo <> coalesce(p_ativo, true) then 'Situação: ' ||
          case when coalesce(p_ativo, true) then 'ativa' else 'inativa' end end), ''), 'Salvou sem mudanças'));
  end if;
  return v_id;
end $$;

create or replace function loc_definir_diretoria_usuario(p_usuario_nome text, p_usuario_id bigint, p_diretoria_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  u loc_usuarios;
  v_a text;
  v_b text;
begin
  select * into u from loc_usuarios where id = p_usuario_id;
  if not found then raise exception 'Usuário não encontrado.'; end if;
  select nome into v_a from loc_diretorias where id = u.diretoria_id;
  select nome into v_b from loc_diretorias where id = p_diretoria_id;
  update loc_usuarios set diretoria_id = p_diretoria_id where id = p_usuario_id;
  perform loc_int_log(v, 'editou', null, null, 'Usuário: ' || u.nome,
    'Diretoria do usuário: ' || coalesce(v_a, 'vazio') || ' → ' || coalesce(v_b, 'vazio'));
end $$;

-- Junta nomes digitados de jeitos diferentes. O histórico continua com o nome original,
-- mas passa a aparecer com o nome oficial (view loc_historico_view).
create or replace function loc_juntar_usuarios(p_usuario_nome text, p_origem_id bigint, p_destino_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  v_o text;
  v_d text;
begin
  select nome into v_o from loc_usuarios where id = p_origem_id;
  select nome into v_d from loc_usuarios where id = p_destino_id and unido_a_id is null;
  if v_o is null or v_d is null or p_origem_id = p_destino_id then raise exception 'Escolha dois usuários diferentes.'; end if;
  update loc_usuarios set unido_a_id = p_destino_id where id = p_origem_id or unido_a_id = p_origem_id;
  perform loc_int_log(v, 'excluiu', null, null, 'Usuário: ' || v_o,
    'Nome "' || v_o || '" juntado em "' || v_d || '"');
end $$;

-- Importação em lote: tudo ou nada, numa transação.
-- p_linhas: [{ aba, linha, obra_nome, diretoria_nome, gestor_nome, categoria_nome, dados: {...como loc_salvar_locacao} }]
create or replace function loc_importar(p_usuario_nome text, p_arquivo text, p_linhas jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v text := loc_int_usuario(p_usuario_nome);
  r jsonb;
  d jsonb;
  v_obra bigint;
  v_dir bigint;
  v_cat bigint;
  v_res jsonb;
  n_novas int := 0;
  n_atual int := 0;
  n_obras int := 0;
begin
  for r in select * from jsonb_array_elements(coalesce(p_linhas, '[]'::jsonb)) loop
    begin
      d := coalesce(r -> 'dados', '{}'::jsonb);
      -- obra pelo nome; cria se não existir
      select id into v_obra from loc_obras where loc_normalizar(nome) = loc_normalizar(r ->> 'obra_nome');
      if v_obra is null then
        if coalesce(trim(r ->> 'obra_nome'), '') = '' then raise exception 'Obra / centro de custo obrigatório'; end if;
        select id into v_dir from loc_diretorias where loc_normalizar(nome) = loc_normalizar(r ->> 'diretoria_nome');
        if v_dir is null then raise exception 'Diretoria "%" não existe', coalesce(r ->> 'diretoria_nome', ''); end if;
        insert into loc_obras (nome, diretoria_id, gestor_nome)
        values (regexp_replace(trim(r ->> 'obra_nome'), '\s+', ' ', 'g'), v_dir, nullif(trim(r ->> 'gestor_nome'), ''))
        returning id into v_obra;
        n_obras := n_obras + 1;
        perform loc_int_log(v, 'criou', null, v_obra, 'Obra: ' || (r ->> 'obra_nome'), 'Obra cadastrada pela importação');
      end if;
      -- categoria (imóveis sempre na categoria de imóveis)
      if r ->> 'aba' = 'Imóveis' then
        v_cat := loc_int_categoria(v, loc_cat_imovel());
      else
        v_cat := loc_int_categoria(v, r ->> 'categoria_nome');
      end if;
      d := d || jsonb_build_object('obra_id', v_obra, 'categoria_id', v_cat) - 'categoria_nova';
      v_res := loc_int_gravar(v, d, true);
      if (v_res ->> 'novo')::boolean then n_novas := n_novas + 1; else n_atual := n_atual + 1; end if;
    exception when others then
      raise exception 'Aba %, linha %: %', coalesce(r ->> 'aba', '?'), coalesce(r ->> 'linha', '?'), sqlerrm;
    end;
  end loop;
  perform loc_int_log(v, 'importou', null, null, p_arquivo,
    n_novas || ' incluídas · ' || n_atual || ' atualizadas'
    || case when n_obras > 0 then ' · ' || n_obras || ' obras novas' else '' end);
  return jsonb_build_object('incluidas', n_novas, 'atualizadas', n_atual, 'obras_novas', n_obras);
end $$;


